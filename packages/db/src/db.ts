import { Kysely, MysqlDialect, PostgresDialect, type MysqlPool as KyselyMysqlPool } from 'kysely'
import pg from 'pg'
import { createPool as createMysqlPool, type Pool as MysqlPool, type PoolOptions } from 'mysql2'
import type { DB } from './types.js' // generated by codegen (Task 5); use `any` until then
import { vendorFromUrl, type DbVendor } from './vendor.js'

export type { DbVendor } from './vendor.js'

let pool: pg.Pool | undefined
let mysqlPool: MysqlPool | undefined
let db: Kysely<DB> | undefined

function databaseUrl(): string {
  const url = process.env.DATABASE_URL
  if (!url) throw new Error('DATABASE_URL is not set')
  return url
}

/** The vendor the current DATABASE_URL points at. Throws on an unsupported scheme. */
export function dbVendor(): DbVendor {
  return vendorFromUrl(databaseUrl())
}

export function getPool(): pg.Pool {
  if (!pool) {
    const connectionString = databaseUrl()
    if (vendorFromUrl(connectionString) !== 'postgresql') {
      throw new Error('getPool() is PostgreSQL-only; DATABASE_URL is a mysql:// URL')
    }
    pool = new pg.Pool({ connectionString, max: 10 })
  }
  return pool
}

/**
 * mysql2 pool options for the Node API. The session is pinned to UTC: `timezone: 'Z'`
 * makes datetime(6) values read and write as UTC instants (PostgreSQL timestamptz
 * equivalent), and BIGINT comes back as a string like pg's int8.
 */
export function mysqlPoolOptions(uri: string): PoolOptions {
  return {
    uri,
    connectionLimit: 10,
    timezone: 'Z',
    supportBigNumbers: true,
    bigNumberStrings: true,
    typeCast: castMysqlValue,
  }
}

// MySQL has no boolean type: `boolean` columns are tinyint(1). Hand them back as
// true/false so the rows match what pg returns.
function castMysqlValue(
  field: { type: string; length: number; string(): string | null },
  next: () => unknown,
): unknown {
  if (field.type === 'TINY' && field.length === 1) {
    const value = field.string()
    return value === null ? null : value === '1'
  }
  return next()
}

function getMysqlPool(url: string): MysqlPool {
  if (!mysqlPool) {
    mysqlPool = createMysqlPool(mysqlPoolOptions(url))
    // Pin the session time zone too, so CURRENT_TIMESTAMP-style defaults agree with UTC.
    mysqlPool.on('connection', (conn) => {
      conn.query("set time_zone = '+00:00'", (err) => {
        if (err) conn.destroy()
      })
    })
  }
  return mysqlPool
}

export function getDb(): Kysely<DB> {
  if (!db) {
    const url = databaseUrl()
    const vendor = vendorFromUrl(url)
    db =
      vendor === 'mysql'
        ? new Kysely<DB>({ dialect: new MysqlDialect({ pool: getMysqlPool(url) as KyselyMysqlPool }) })
        : new Kysely<DB>({ dialect: new PostgresDialect({ pool: getPool() }) })
  }
  return db
}

export async function closeDb(): Promise<void> {
  // Kysely's destroy() ends whichever pool the dialect holds.
  await db?.destroy()
  db = undefined
  pool = undefined
  mysqlPool = undefined
}
